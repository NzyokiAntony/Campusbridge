
const CAMPUSBRIDGE_INSTRUCTIONS = `
You are CampusBridge AI Assistant, a helpful virtual guide for students
joining or studying at Murang'a University of Technology (MUT), Kenya.

Your role is to help users understand CampusBridge services, including:
- Student registration and admission guidance.
- Provisional student IDs.
- Campus locations and facilities.
- Hostel and off-campus accommodation guidance.
- Dining options.
- Student support and university procedures.
- Parent and guardian guidance.

IMPORTANT RULES:
1. Use simple, friendly and understandable English.
2. Give clear, practical answers.
3. Do not invent university fees, deadlines, official policies,
   accommodation availability or admission decisions.
4. If you do not know an official detail, say so and direct the
   student to confirm with MUT.
5. Never claim that CampusBridge is an official university system.
6. Explain that provisional IDs generated by the prototype are
   not replacements for official MUT student identification.
7. Do not claim to have accessed university records or verified
   a student's registration.
8. Keep answers relevant to the user's question.
`;

type ChatMessage = {
  role: "user" | "assistant";
  content: string;
};

export async function POST(request: Request): Promise<Response> {
  try {
    const apiKey = process.env.OPENAI_API_KEY;

    if (!apiKey) {
      return Response.json(
        { error: "The AI API key is not configured on the server." },
        { status: 500 }
      );
    }

    const body = await request.json();

    const messages = body.messages as ChatMessage[];

    if (!Array.isArray(messages) || messages.length === 0) {
      return Response.json(
        { error: "Please enter a question." },
        { status: 400 }
      );
    }

    const validMessages = messages.filter(
      (message) =>
        message &&
        (message.role === "user" || message.role === "assistant") &&
        typeof message.content === "string"
    );

    if (
      validMessages.length === 0 ||
      validMessages[validMessages.length - 1].role !== "user"
    ) {
      return Response.json(
        { error: "Your message could not be processed." },
        { status: 400 }
      );
    }

    const aiResponse = await fetch(
      "https://api.openai.com/v1/responses",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${apiKey}`,
        },
        body: JSON.stringify({
          model: "gpt-5.5",
          instructions: CAMPUSBRIDGE_INSTRUCTIONS,
          input: validMessages,
        }),
      }
    );

    const result = await aiResponse.json();

    if (!aiResponse.ok) {
      console.error("OpenAI API error:", result);

      return Response.json(
        {
          error:
            result.error?.message ||
            "The AI service could not process your request.",
        },
        { status: aiResponse.status }
      );
    }

    const reply =
      result.output_text ||
      result.output
        ?.flatMap((item: { content?: Array<{ type?: string; text?: string }> }) =>
          item.content || []
        )
        .filter((item: { type?: string }) => item.type === "output_text")
        .map((item: { text?: string }) => item.text || "")
        .join("\n");

    if (!reply) {
      return Response.json(
        { error: "The AI returned an empty response. Please try again." },
        { status: 502 }
      );
    }

    return Response.json({ reply });
  } catch (error) {
    console.error("CampusBridge backend error:", error);

    return Response.json(
      { error: "Unable to connect to the AI service. Please try again." },
      { status: 500 }
    );
  }
}
